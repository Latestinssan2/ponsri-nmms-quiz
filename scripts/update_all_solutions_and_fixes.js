function processQuizObject(quizObj) {
  let updatedSolutions = 0;
  let correctedAnswers = 0;

  quizObj.questions.forEach((q) => {
    // Apply answer corrections
    if (corrections[q.id]) {
      const corr = corrections[q.id];
      q.correct_index = corr.correct_index;
      q.correct_answer = corr.correct_answer;
      q.answer = corr.answer;
      correctedAnswers++;
    }
    // Ensure answer matches correct_index
    q.answer = q.correct_index;
    q.correct_answer = q.options[q.correct_index];

    // Apply explanation
    if (explanations[q.id]) {
      q.explanation = explanations[q.id];
      updatedSolutions++;
    } else {
      console.warn(`Missing explanation for Q${q.id}`);
    }
  });

  return { updatedSolutions, correctedAnswers };
}

